-- 성경 질문 — 질문·응답 기록 · 관리자 열람 기록 · 고쳐 쓰는 목록 · 설교 색인 (2026-09-18)
--
-- 기준 문서: docs/BIBLE_QA_DOCTRINE.md (§B-10 기록 규칙) · docs/BIBLE_QA_SERMONS.md
--
-- 공통 정책 (scripts/migration-login-features.sql 과 동일)
--  * user_id 는 saint.yebom.org 의 text id. Supabase Auth 를 쓰지 않으므로 auth.uid() 는 항상 null.
--    그래서 RLS 를 켜되 정책은 두지 않는다 = anon/authenticated 는 아무것도 못 읽고 못 쓴다.
--    서버(supabaseAdmin, service_role)만 접근하며 항상 user_id 로 스코프한다.
--    **enable row level security 를 빠뜨리면 anon 키로 전 교인의 질문 내용이 그대로 노출된다.**
--    (anon 키는 NEXT_PUBLIC_ 이라 브라우저 번들에 실린다. 실제로 그 한 줄을 빠뜨려
--     열려 있는 표가 이 DB 에 이미 있다 — plan.md 의 RLS 점검 항목을 함께 볼 것.)
--  * user_id 에 FK 를 걸지 않는다 — 교인 계정 표가 이 스키마에 없다.
--  * id 는 bigint generated by default as identity (always 로 하면 id 를 실어 보내는 코드가 실패한다).
--  * UNIQUE 는 인라인 제약이 아니라 별도 create unique index — 같은 파일을 두 번 실행해도 안전해야 한다.
--  * 멱등 — 여러 번 실행해도 안전하다.

-- ══════════════════════════════════════════════════════════════════
-- 1. 질문 한 건 = 한 행
-- ══════════════════════════════════════════════════════════════════
create table if not exists public.ai_questions (
  id              bigint      generated by default as identity primary key,
  user_id         text        not null,
  -- 관리자 화면에 띄울 이름. 조인할 계정 표가 없어 질문 시점의 세션 이름을 복사해 둔다.
  user_name       text,

  -- 어느 절을 보고 물었는가 (§4 "질문에 다른 구절이 나오지 않으면 고른 본문을 두고 묻는 것으로 읽는다")
  book_code       varchar(10) not null,
  chapter         smallint    not null,
  verse_start     smallint    not null,
  verse_end       smallint,
  version         varchar(10),
  -- 화면·프롬프트에 그대로 쓰는 표기. 예: "누가복음 5:1-11"
  verses_ref      text,

  question        text        not null,
  -- 글로 물었나 말로 물었나 (말은 STT 를 거쳐 글이 된 것)
  input_kind      varchar(10) not null default 'text',

  -- 선별 결과: allow · deny · crisis · error(게이트 실패 → 통과시킨 건)
  gate_result     varchar(10) not null,
  -- 위기 건은 관리자 화면에서 눈에 띄게 표시해 super_admin 이 처리한다(§B-10).
  -- gate_result 와 따로 두는 까닭: 뒤에 사람이 '위기가 아니었다' 고 판정해도
  -- 그때 기계가 무엇으로 갈랐는지는 지워지지 않아야 한다.
  is_crisis       boolean     not null default false,
  -- 위기 판정을 사람이 검토한 결과. null = 아직 안 봤다
  crisis_reviewed boolean,
  crisis_note     text,

  -- single = 한 AI, chorus = 셋이 함께
  mode            varchar(10) not null default 'single',
  -- 가정교회 자료 블록을 붙여 보냈는가 (§B-12)
  housechurch     boolean     not null default false,

  -- 어떤 기준으로 답했는가 (§B-10 · §B-11). 문제가 된 답을 되짚을 수 있어야 한다.
  prompt_version  varchar(20) not null default 'v1',
  -- DB 에 둔 목록(이단·가정교회·위기창구·삶공부)의 갱신 시각
  lists_synced_at timestamptz,

  -- 교인이 저장을 눌렀는가. 교인이 지우면 false 로 내려가고 이 행은 남는다(§B-10).
  saved           boolean     not null default false,
  saved_at        timestamptz,

  asked_at        timestamptz not null default now()
);

-- 내 기록 조회(본인) + 관리자 화면의 최근 목록. 선두가 user_id 라 user_id 단독 인덱스는 따로 두지 않는다.
create index if not exists ai_questions_user_asked_idx
  on public.ai_questions (user_id, asked_at desc);

-- 본문에서 이 절에 내가 물어 둔 것을 찾는 자리 (saved 만 보인다)
create index if not exists ai_questions_verse_idx
  on public.ai_questions (user_id, book_code, chapter, verse_start);

-- 관리자 화면: 위기 건 먼저. 부분 인덱스라 전체 표가 커져도 값이 싸다.
create index if not exists ai_questions_crisis_idx
  on public.ai_questions (asked_at desc) where is_crisis;

-- 관리자 화면: 전체 최근 순
create index if not exists ai_questions_asked_idx
  on public.ai_questions (asked_at desc);

alter table public.ai_questions enable row level security;
-- 정책 없음: supabaseAdmin(service_role) 전용. 본인 조회는 항상 user_id 로 스코프한다.


-- ══════════════════════════════════════════════════════════════════
-- 2. 답 = 모델 하나가 준 한 칸
--    한 질문에 1개(single) 또는 3개(chorus). 실패한 칸도 행으로 남긴다 —
--    그날 Gemini 가 왜 빈 칸이었나를 뒤에 알 수 있어야 한다.
-- ══════════════════════════════════════════════════════════════════
create table if not exists public.ai_question_answers (
  id             bigint      generated by default as identity primary key,
  question_id    bigint      not null references public.ai_questions(id) on delete cascade,

  -- 화면의 칸. gemini · chatgpt · claude
  column_key     varchar(20) not null,
  -- 우리가 요청한 별칭 (gemini-flash · chatgpt · claude-sonnet)
  provider_alias varchar(40),
  -- 게이트웨이가 돌려준 실제 모델 이름. 칸 라벨의 진실은 이 값뿐이다 —
  -- 응답의 provider 필드는 계열명으로 정규화돼 와서(gemini-flash → "gemini")
  -- 강등된 답과 정상 답을 구분하지 못한다(2026-09-18 실측).
  model          varchar(80),

  ok             boolean     not null default false,
  -- **모델이 실제로 준 글을 그대로 남긴다.** 화면에 보인 것은 없는 구절 표시를 지운 판이지만,
  -- 모델이 없는 구절을 지어냈다는 사실은 기록에 남아야 잡을 수 있다(§B-5).
  content        text,
  -- 지운 주소. 이 값이 늘면 그 모델이 구절을 지어내고 있다는 뜻이다.
  removed_refs   text[],
  -- 실패 사유. MODEL_MISMATCH · EMPTY_RESPONSE · TIMEOUT · AI_ERROR 400 …
  error          text,

  input_tokens   integer,
  output_tokens  integer,
  elapsed_ms     integer,

  -- §B-6 '이 답이 이상합니다'
  reported       boolean     not null default false,
  report_reason  text,
  reported_at    timestamptz,

  created_at     timestamptz not null default now()
);

create index if not exists ai_question_answers_q_idx
  on public.ai_question_answers (question_id);

-- 관리자 화면: 신고된 답 먼저
create index if not exists ai_question_answers_reported_idx
  on public.ai_question_answers (reported_at desc) where reported;

-- 한 질문에 같은 칸이 두 번 들어가지 않는다(다시 묻기는 새 질문 행이다)
create unique index if not exists ai_question_answers_uniq
  on public.ai_question_answers (question_id, column_key);

alter table public.ai_question_answers enable row level security;


-- ══════════════════════════════════════════════════════════════════
-- 3. 관리자 열람 기록 — 열어 본 사실도 남긴다(§B-10)
--    교인에게 화면으로 알리지는 않는다(지휘부 2026-09-18).
-- ══════════════════════════════════════════════════════════════════
create table if not exists public.ai_question_views (
  id             bigint      generated by default as identity primary key,
  viewer_user_id text        not null,
  viewer_name    text,
  -- list = 목록을 열었다 · detail = 한 건을 펼쳤다 · delete = 지웠다 · export = 내려받았다
  action         varchar(20) not null,
  -- 목록 열람은 null
  question_id    bigint,
  -- 목록 열람 때의 조건(기간·검색어 등)을 남겨 두면 뒤에 무엇을 본 것인지 알 수 있다
  detail         text,
  viewed_at      timestamptz not null default now()
);

-- question_id 에 FK 를 걸지 않는다 — 질문이 지워진 뒤에도 지웠다는 기록이 남아야 한다.
create index if not exists ai_question_views_viewed_idx
  on public.ai_question_views (viewed_at desc);

alter table public.ai_question_views enable row level security;


