-- 4. 관리자 화면에서 고쳐 쓰는 네 가지 목록 (§B-11)
--    ① 이단 목록 ② 가정교회 자료 ③ 위기 상담 창구 ④ 삶공부 과정 이름
--    교리 기준 본문은 저장소 문서에 그대로 둔다 — 여기에는 자주 바뀌는 것만.
-- ══════════════════════════════════════════════════════════════════
create table if not exists public.qa_lists (
  id         bigint      generated by default as identity primary key,
  -- heresy · housechurch · crisis · lifestudy
  kind       varchar(20) not null,
  sort_order smallint    not null default 0,
  -- 이단 목록이면 단체명, 위기 창구면 창구 이름, 삶공부면 과정 이름
  title      text        not null,
  -- 이단 목록이면 무엇이 갈라지는가, 위기 창구면 번호와 여는 시간
  body       text,
  -- 사람만 보는 근거·출처(프롬프트에 넣지 않는다)
  note       text,
  enabled    boolean     not null default true,
  updated_at timestamptz not null default now(),
  updated_by text
);

create index if not exists qa_lists_kind_idx
  on public.qa_lists (kind, sort_order);

-- 같은 갈래에 같은 제목을 두 번 넣지 않는다
create unique index if not exists qa_lists_kind_title_uniq
  on public.qa_lists (kind, title);

alter table public.qa_lists enable row level security;


