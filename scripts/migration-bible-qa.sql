-- 5. 설교 색인 — 이 구절을 다룬 우리 교회 설교 카드 (docs/BIBLE_QA_SERMONS.md)
--    AI 에게 주지 않는다. 앱이 답 아래에 카드로만 붙인다.
-- ══════════════════════════════════════════════════════════════════
create table if not exists public.sermons (
  id           bigint      generated by default as identity primary key,
  preached_on  date        not null,
  title        text        not null,
  preacher     text,
  video_url    text,
  -- 파일의 -요약- 절. 카드에는 첫 문단만 보인다.
  summary      text,
  -- 파일의 -적용- 절. 카드에 보이지 않는다(지휘부 2026-09-18) — 3단계와 뒷날을 위해 담아만 둔다.
  applications text[],

  -- 드라이브 원본 추적. modified 가 새로울 때만 다시 들여온다.
  source_file_id     text,
  source_name        text,
  source_modified_at timestamptz,
  ingested_at        timestamptz not null default now()
);

-- 같은 설교를 두 번 넣지 않는다. 파일 이름이 바뀌어도 날짜+제목이면 같은 설교다.
create unique index if not exists sermons_date_title_uniq
  on public.sermons (preached_on, title);

create index if not exists sermons_preached_idx
  on public.sermons (preached_on desc);

-- 공개 자료다 — 비로그인 교인에게도 카드가 보여야 한다.
-- 그래도 RLS 를 켜고 정책은 두지 않는다: 읽기는 반드시 서버 라우트(supabaseAdmin)를 거친다.
-- (anon 정책을 열면 브라우저에서 직접 긁을 수 있게 되고, 그만큼 조회 패턴을 통제할 수 없다.)
alter table public.sermons enable row level security;


create table if not exists public.sermon_refs (
  id          bigint      generated by default as identity primary key,
  sermon_id   bigint      not null references public.sermons(id) on delete cascade,
  -- main = 머리글의 본문 · quoted = 요약·적용 안에 인용된 구절
  kind        varchar(10) not null default 'main',
  book_code   varchar(10) not null,
  chapter     smallint    not null,
  verse_start smallint,
  verse_end   smallint
);

-- 카드 조회의 유일한 진입 — 이 인덱스가 없으면 수 ms 전제가 깨진다.
create index if not exists sermon_refs_lookup_idx
  on public.sermon_refs (book_code, chapter);

create index if not exists sermon_refs_sermon_idx
  on public.sermon_refs (sermon_id);

-- 같은 설교에 같은 구절을 두 번 넣지 않는다. 절이 null 인 장 전체도 한 번만.
create unique index if not exists sermon_refs_uniq
  on public.sermon_refs (sermon_id, kind, book_code, chapter,
                         coalesce(verse_start, 0), coalesce(verse_end, 0));

alter table public.sermon_refs enable row level security;


create table if not exists public.sermon_ingest_runs (
  id         bigint      generated by default as identity primary key,
  ran_at     timestamptz not null default now(),
  -- cron · manual
  trigger    varchar(10) not null default 'cron',
  scanned    integer     not null default 0,
  inserted   integer     not null default 0,
  updated    integer     not null default 0,
  skipped    integer     not null default 0,
  -- 못 읽은 파일과 까닭. 조용히 넘기면 없는 설교가 되고 아무도 모른다.
  failures   jsonb,
  elapsed_ms integer,
  error      text
);

create index if not exists sermon_ingest_runs_ran_idx
  on public.sermon_ingest_runs (ran_at desc);

alter table public.sermon_ingest_runs enable row level security;


