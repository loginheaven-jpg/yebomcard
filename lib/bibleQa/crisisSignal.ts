/**
 * 성경 질문 — 게이트웨이가 늦을 때도 위기를 놓치지 않기 위한 안전망
 *
 * 왜 필요한가(2026-09-18 운영 실측):
 *   선별은 게이트웨이의 `gemini-flash` 가 한다(§A). 그런데 게이트웨이 자체가 느리고 들쭉날쭉하다 —
 *   모델을 부르지 않는 캐시 적중조차 3.9~30.8초, 한 낱말 선별이 10~14초였다. 운영의 첫 두 질문은
 *   **둘 다 선별이 시간 초과로 '통과'** 처리됐다. 문서는 선별 실패를 통과로 두었으니(§A — 값싼 문이
 *   신앙 질문을 막으면 안 된다), 게이트웨이가 늦는 동안은 **위기 신호가 한 번도 잡히지 않는다.**
 *
 * 무엇을 하는가:
 *   여기 있는 말은 **그 자체로 위기를 판정하지 않는다.** 선별이 제때 답하면 선별을 따른다
 *   ("욥은 왜 죽고 싶다고 했나요" 는 선별이 allow 로 가른다). 이 말이 하는 일은 하나 —
 *   **선별이 실패했을 때 통과시킬지 막을지**를 가른다.
 *     - 이 말이 있고 선별이 실패 → **위기로 본다**(막는다, 모델을 부르지 않는다)
 *     - 이 말이 없고 선별이 실패 → 문서대로 통과
 *   놓치는 쪽이 기다리거나 잘못 막는 쪽보다 나쁘다. 잘못 막으면 상담 창구가 보일 뿐이다.
 *
 * 말 고르기: **1인칭·지금의 고통**이 분명한 꼴만 둔다. '자살한 사람은 지옥에 갑니까' 처럼
 * 주제로 묻는 말은 걸리지 않게 한다(§A 보기에서 그 질문은 allow 다).
 */

const SIGNALS: RegExp[] = [
  // 죽음·사라짐을 바라는 말
  /죽고\s*싶/,
  /사라지고\s*싶/,
  /없어지고\s*싶/,
  /살고\s*싶지\s*않/,
  /살\s*(이유|의미)가\s*없/,
  /(삶|인생|목숨)을?\s*끝내/,
  /자살\s*(하고\s*싶|할까|하려|생각|충동|시도)/,
  /극단적\s*(인\s*)?(선택|생각)/,
  // 자해
  /자해(를|했|하|해)/,
  // 폭력·학대 (주제가 아니라 겪고 있다는 말)
  /때립니다|때려요/,
  /맞고\s*(있|살)/,
  /학대(를)?\s*(당|받)/,
  /성(폭력|추행)을?\s*당/,
  /강간/,
  // 약·치료를 끊음(§A — "약이나 치료를 끊었다")
  /(약|치료|투약)을?\s*(끊었|끊고|안\s*먹|그만\s*먹)/,
  // 환청·환시
  /환청|환시/,
];

/** 질문에 위기를 시사하는 1인칭 말이 있는가 — 선별이 실패했을 때만 쓰인다. */
export function hasCrisisSignal(question: string): boolean {
  const q = (question ?? "").replace(/\s+/g, " ");
  return SIGNALS.some((re) => re.test(q));
}
